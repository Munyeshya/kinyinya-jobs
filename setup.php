<?php
require_once __DIR__ . '/includes/config.php';

if (session_status() === PHP_SESSION_NONE) session_start();

$configured = is_file(__DIR__ . '/includes/local-config.php');
$success = false;
$error = '';

function kj_setup_run_sql(PDO $pdo, string $file): void {
    $sql = file_get_contents($file);
    if ($sql === false) throw new RuntimeException('Could not read ' . basename($file));
    $sql = preg_replace('/^\s*--.*$/m', '', $sql);
    foreach (preg_split('/;\s*(?:\r?\n|$)/', $sql) as $statement) {
        $statement = trim($statement);
        if ($statement !== '') $pdo->exec($statement);
    }
}

if (empty($_SESSION['setup_csrf'])) $_SESSION['setup_csrf'] = bin2hex(random_bytes(24));

if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$configured) {
    try {
        if (!hash_equals($_SESSION['setup_csrf'], $_POST['csrf'] ?? '')) {
            throw new RuntimeException('The setup session expired. Refresh the page and try again.');
        }

        $host = trim($_POST['host'] ?? '127.0.0.1');
        $port = (int) ($_POST['port'] ?? 3306);
        $adminUser = trim($_POST['admin_user'] ?? 'root');
        $adminPass = (string) ($_POST['admin_password'] ?? '');
        $appUser = trim($_POST['app_user'] ?? 'kinyinya_app');
        $appPass = (string) ($_POST['app_password'] ?? 'kinyinya_dev_password');

        if (!preg_match('/^[A-Za-z0-9_]+$/', $appUser)) {
            throw new RuntimeException('The application username may contain only letters, numbers, and underscores.');
        }
        if ($port < 1 || $port > 65535 || $host === '' || $adminUser === '' || $appPass === '') {
            throw new RuntimeException('Complete all required database fields.');
        }

        $admin = new PDO("mysql:host={$host};port={$port};charset=utf8mb4", $adminUser, $adminPass, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_EMULATE_PREPARES => false,
        ]);

        kj_setup_run_sql($admin, __DIR__ . '/database/schema.sql');
        $quotedUser = '`' . str_replace('`', '``', $appUser) . '`';
        $quotedPassword = $admin->quote($appPass);
        $admin->exec("CREATE USER IF NOT EXISTS '{$appUser}'@'localhost' IDENTIFIED BY {$quotedPassword}");
        $admin->exec("ALTER USER '{$appUser}'@'localhost' IDENTIFIED BY {$quotedPassword}");
        $admin->exec("GRANT ALL PRIVILEGES ON kinyinya_jobs.* TO '{$appUser}'@'localhost'");
        $admin->exec('FLUSH PRIVILEGES');

        if (!empty($_POST['demo_data'])) {
            kj_setup_run_sql($admin, __DIR__ . '/database/seed.sql');
        }

        $settings = [
            'DB_HOST' => $host,
            'DB_PORT' => (string) $port,
            'DB_NAME' => 'kinyinya_jobs',
            'DB_USER' => $appUser,
            'DB_PASS' => $appPass,
        ];
        $contents = "<?php\n// Generated by setup.php. Keep this file private and do not commit it.\nreturn " . var_export($settings, true) . ";\n";
        if (file_put_contents(__DIR__ . '/includes/local-config.php', $contents, LOCK_EX) === false) {
            throw new RuntimeException('The database was created, but includes/local-config.php could not be written. Check folder permissions.');
        }
        $configured = true;
        $success = true;
        unset($_SESSION['setup_csrf']);
    } catch (Throwable $exception) {
        $error = $exception->getMessage();
    }
}
