  <?php if ($success): ?>
    <div class="flash">Setup completed successfully. The application is ready.</div>
    <p><a class="btn btn-primary" href="<?= htmlspecialchars(kj_url('index.php')) ?>">Open Kinyinya Jobs</a></p>
  <?php elseif ($configured): ?>
    <div class="flash">This copy is already configured.</div>
    <p><a class="btn btn-primary" href="<?= htmlspecialchars(kj_url('index.php')) ?>">Open Kinyinya Jobs</a></p>
    <p style="color:var(--ink-soft)">To configure a different database, remove <code>includes/local-config.php</code> and return to this page.</p>
  <?php else: ?>
    <?php if ($error): ?><div class="flash" style="background:var(--brick-100); color:var(--brick-600); border-color:var(--brick-600)"><?= htmlspecialchars($error) ?></div><?php endif; ?>
    <form method="post" class="card">
      <input type="hidden" name="csrf" value="<?= htmlspecialchars($_SESSION['setup_csrf']) ?>">
      <h3>MySQL administrator connection</h3>
      <p style="color:var(--ink-soft); margin-top:0">For XAMPP, the username is usually <strong>root</strong> with an empty password. For MySQL Workbench, enter the root password saved for your local connection.</p>
      <div class="grid-2">
        <div class="field"><label for="host">Server</label><input id="host" name="host" required value="<?= htmlspecialchars($_POST['host'] ?? '127.0.0.1') ?>"></div>
        <div class="field"><label for="port">Port</label><input id="port" name="port" type="number" required value="<?= htmlspecialchars($_POST['port'] ?? '3306') ?>"></div>
      </div>
      <div class="grid-2">
        <div class="field"><label for="admin_user">Administrator username</label><input id="admin_user" name="admin_user" required value="<?= htmlspecialchars($_POST['admin_user'] ?? 'root') ?>"></div>
        <div class="field"><label for="admin_password">Administrator password</label><input id="admin_password" name="admin_password" type="password" autocomplete="current-password"></div>
      </div>

      <h3>Application database account</h3>
      <div class="grid-2">
        <div class="field"><label for="app_user">Application username</label><input id="app_user" name="app_user" required value="<?= htmlspecialchars($_POST['app_user'] ?? 'kinyinya_app') ?>"></div>
        <div class="field"><label for="app_password">Application password</label><input id="app_password" name="app_password" type="password" required value="<?= htmlspecialchars($_POST['app_password'] ?? 'kinyinya_dev_password') ?>"></div>
      </div>
      <div class="field"><label><input name="demo_data" type="checkbox" value="1" checked style="width:auto"> Load demonstration employers, seekers, jobs, and applications</label></div>
      <button class="btn btn-primary" type="submit">Create database and finish setup</button>
    </form>
  <?php endif; ?>
